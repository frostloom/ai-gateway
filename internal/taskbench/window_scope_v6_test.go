func TestWindowV6Declaration(t *testing.T) {
	s, p, b := windowScopeInputs(t)
	caps := windowV6TestCaps()
	scope, err := prepareFullWindowScopeV6(s, p, 28, caps, b, windowV6BaselineSHA, windowBudget130ApprovalSHA)
	if err != nil {
		t.Fatal(err)
	}
	_, totals, err := validateFullWindowScope(scope, s, p, b)
	if err != nil || totals.ModelCap != 85000000 || totals.JEVCap != 600000 || totals.DefinedUserTurns != 11772 {
		t.Fatal(totals, err)
	}
	for _, mode := range []string{"width", "vector", "overflow", "baseline", "approval"} {
		t.Run(mode, func(t *testing.T) {
			c := windowV6TestCaps()
			width := 28
			base, approval := windowV6BaselineSHA, windowBudget130ApprovalSHA
			switch mode {
			case "width":
				width = 27
			case "vector":
				c[0].ModelCap++
				c[1].ModelCap--
			case "overflow":
				c[0].ModelCap = 1<<63 - 1
			case "baseline":
				base = windowV5BaselineSHA
			case "approval":
				approval = windowBudget105ApprovalSHA
			}
			if _, err := prepareFullWindowScopeV6(s, p, width, c, b, base, approval); err == nil {
				t.Fatal("accepted mutation")
			}
		})
	}
}
