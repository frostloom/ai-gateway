func TestWindowV7ScopeFrozenVector(t *testing.T) {
	s, p, b := windowScopeInputs(t)
	scope, err := prepareFullWindowScopeWithBounds(s, p, 28, windowV7TestCaps(), b, 84510611, 650855)
	if err != nil {
		t.Fatal(err)
	}
	scope.Schema = "full-window-scope.v7"
	scope.BaselineEvidenceSHA256 = "ccf528106789daf05a61c8d8f4e5f72d3a29eea65d78a6f81afb85f4e1ea45ad"
	scope.BudgetApprovalSHA256 = windowBudget130ApprovalSHA
	_, totals, err := validateFullWindowScope(scope, s, p, b)
	if err != nil || totals.ModelCap != 84500000 || totals.JEVCap != 600000 || totals.DefinedUserTurns != 11772 {
		t.Fatalf("v7 fixed scope: %+v %v", totals, err)
	}
	scope.Windows[0].ModelCap++
	scope.Windows[1].ModelCap--
	if _, _, err = validateFullWindowScope(scope, s, p, b); err == nil {
		t.Fatal("changed fixed vector accepted")
	}
}
