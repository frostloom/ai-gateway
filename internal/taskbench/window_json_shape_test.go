// Catch the allocation regression that reconstructs every primitive value just
// to validate a document before decoding that same document into its real type.
func TestWindowTypedJSONValidationAllocations(t *testing.T) {
	var input strings.Builder
	input.WriteString(`{"items":[`)
	for i := 0; i < 4096; i++ {
		if i != 0 {
			input.WriteByte(',')
		}
		input.WriteString(strconv.Itoa(i))
	}
	input.WriteString(`]}`)
	raw := []byte(input.String())
	type document struct {
		Items []int `json:"items"`
	}
	var got document
	allocations := testing.AllocsPerRun(3, func() {
		got = document{}
		if err := decodeWindowActualJSON(raw, &got); err != nil {
			t.Fatal(err)
		}
	})
	if len(got.Items) != 4096 || got.Items[0] != 0 || got.Items[4095] != 4095 {
		t.Fatal("typed values changed")
	}
	if allocations > 128 {
		t.Fatalf("validation materialized primitive values: %.0f allocations, want <=128", allocations)
	}
	t.Logf("typed decode allocations=%.0f", allocations)
}

func TestWindowJSONShapeStrictPolicy(t *testing.T) {
	cases := []struct {
		name, raw string
		valid     bool
		nonnull   bool
	}{
		{"empty", `{}`, true, true},
		{"values", ` {"a":[1,-0,1e9999,true,false,"null","\\\""],"b":{}} `, true, true},
		{"nullable", `{"a":[{"b":null}]}`, true, false},
		{"null_readiness", `{"a":[{"b":null}]}`, false, true},
		{"duplicate", `{"a":1,"a":2}`, false, false},
		{"decoded_key", `{"a":1,"\u0061":2}`, false, false},
		{"decoded_slash", `{"a/b":1,"a\/b":2}`, false, false},
		{"surrogate_replacement", `{"\ud800":1,"�":2}`, false, false},
		{"surrogate_pair", `{"\ud83d\ude00":1,"😀":2}`, false, false},
		{"separate_objects", `{"a":{"k":1},"b":{"k":2}}`, true, true},
		{"nested_duplicate", `{"a":[{"k":1,"k":2}]}`, false, false},
		{"null_before_duplicate", `{"n":null,"k":1,"k":2}`, false, true},
		{"malformed", `{"k":}`, false, false},
		{"trailing", `{} {}`, false, false},
		{"trailing_scalar", `{} false`, false, false},
		{"root_array", `[]`, false, false},
		{"root_null", `null`, false, false},
		{"invalid_utf8", string([]byte{'{', '"', 0xff, '"', ':', '1', '}'}), false, false},
		{"primitive_depth128", `{"a":` + strings.Repeat("[", 127) + "0" + strings.Repeat("]", 127) + "}", true, true},
		{"primitive_depth129", `{"a":` + strings.Repeat("[", 128) + "0" + strings.Repeat("]", 128) + "}", false, true},
		{"empty_container_depth128", `{"a":` + strings.Repeat("[", 128) + strings.Repeat("]", 128) + "}", true, true},
		{"empty_container_depth129", `{"a":` + strings.Repeat("[", 129) + strings.Repeat("]", 129) + "}", false, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := validateWindowJSONShape([]byte(tc.raw), tc.nonnull)
			if (err == nil) != tc.valid {
				t.Fatalf("accepted=%t, want=%t: %v", err == nil, tc.valid, err)
			}
			if (err == nil) != originalWindowShapeAccepts([]byte(tc.raw), tc.nonnull) {
				t.Fatal("changed original acceptance")
			}
		})
	}
}

func TestWindowJSONShapeTypedDecoderPolicies(t *testing.T) {
	var nullable struct {
		Value *int `json:"value"`
	}
	if err := decodeWindowActualJSON([]byte(`{"value":null}`), &nullable); err == nil {
		t.Fatal("readiness accepted null")
	}
	if err := decodeWindowStoppedV4QualityData([]byte(`{"value":null}`), &nullable); err != nil {
		t.Fatal("quality rejected legitimate null", err)
	}
	if _, err := decodeWindowStoppedV2Recording([]byte(`{"issues":null}`)); err != nil {
		t.Fatal("recording rejected legitimate null", err)
	}
	if err := decodeWindowActualJSON([]byte(`{"unknown":true}`), &nullable); err == nil {
		t.Fatal("readiness accepted unknown field")
	}
	if err := decodeWindowStoppedV4QualityData([]byte(`{"unknown":true}`), &nullable); err == nil {
		t.Fatal("quality accepted unknown field")
	}
	if _, err := decodeWindowStoppedV2Recording([]byte(`{"unknown":true}`)); err == nil {
		t.Fatal("recording accepted unknown field")
	}
}

// The retained token parser is an independent reference implementation, not
// the scanner under test. This also covers malformed inputs generated by fuzz.
func originalWindowShapeAccepts(raw []byte, nonnull bool) bool {
	obj, err := windowJSONObject(raw)
	if err != nil {
		return false
	}
	if !nonnull {
		return true
	}
	var check func(any) bool
	check = func(v any) bool {
		if v == nil {
			return false
		}
		switch value := v.(type) {
		case map[string]any:
			for _, item := range value {
				if !check(item) {
					return false
				}
			}
		case []any:
			for _, item := range value {
				if !check(item) {
					return false
				}
			}
		}
		return true
	}
	return check(obj)
}

func FuzzWindowJSONShapeEquivalent(f *testing.F) {
	for _, seed := range []string{`{}`, `{"a":null}`, `{"a":1,"\u0061":2}`, `{"a":[true,1e99,"\\\""]}`, `{} {}`, `{"\ud800":0,"�":1}`} {
		f.Add([]byte(seed), false)
		f.Add([]byte(seed), true)
	}
	f.Fuzz(func(t *testing.T, raw []byte, nonnull bool) {
		if len(raw) > 8192 {
			t.Skip()
		}
		got := validateWindowJSONShape(raw, nonnull) == nil
		if got != originalWindowShapeAccepts(raw, nonnull) {
			t.Fatalf("acceptance changed nonnull=%t raw=%q", nonnull, raw)
		}
	})
}
