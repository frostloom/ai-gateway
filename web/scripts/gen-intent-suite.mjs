/** 稳定伪随机（不用 Math.random，保证可复现） */
function makeRng(seed) {
  let s = seed >>> 0
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0
    return s / 0x100000000
  }
}

/**
 * 判断该说法是否「信息不足、应先反问」。
 *
 * 退款/送订/改套餐这类写操作需要明确参数（金额/订单号/目标档位）。
 * 用户只说「退钱」「我不包月了」时，正确流程是**先探查再反问**，
 * 而不是直接执行 —— 硬要求"直接调工具"会把正确行为判成路由错误。
 *
 * 判据（保守，宁少勿多）：
 *   - 退款类：提到金额或订单号 → 信息足够；只说动作 → 信息不足
 *   - 其余写操作：需要指定目标/档位的才标
 */
function isAskBack(intent, tool, text) {
  if (tool === 'refund_recharge') {
    // 有明确金额（数字）或订单号 → 信息足够
    return !/\d/.test(text) && !/订单/.test(text)
  }
  if (tool === 'change_plan' || tool === 'subscribe_plan') {
    // 明确说了要换/订哪一档 → 信息足够
    return !/(旗舰|标准|月度|pro|plan\s*[a-z0-9]|¥|\d+\s*元)/i.test(text)
  }
  return false
}

const manifest = {
  version: 1,
  generatedBy: 'web/scripts/gen-intent-suite.mjs',
  note: '由结构化模板生成，保证可复现与均衡；非 LLM 自由生成',
  perClass: 100,
  dimensions: Object.keys(DIM_QUOTA),
  classes: [],
  totalSamples: 0,
}

let allCount = 0
for (const [key, suite] of Object.entries(SUITES)) {
  const [intent, tool, risk, needsConfirm] = key.split('|')
  const rng = makeRng(intent.length * 7919 + 13)
  const rows = []
  const used = new Set()

  for (const [dim, quota] of Object.entries(DIM_QUOTA)) {
    const pool = suite[dim] ?? []
    if (!pool.length) {
      throw new Error(`${intent} 缺少维度 ${dim} 的语料池`)
    }
    // 按配额取；池子不够则循环（加序号后缀避免重复文本）
    for (let i = 0; i < quota; i++) {
      let text = pool[i % pool.length]
      if (i >= pool.length) text = `${text}（${Math.floor(i / pool.length) + 1}）`
      if (used.has(text)) {
        let n = 2
        while (used.has(`${text} #${n}`)) n++
        text = `${text} #${n}`
      }
      used.add(text)
      const row = {
        id: `${intent}-${String(rows.length + 1).padStart(3, '0')}`,
        text,
        intent: tool,
        dimension: dim,
        risk,
        needs_confirm: needsConfirm === 'true',
      }
      if (isAskBack(intent, tool, text)) row.ask_back = true
      rows.push(row)
    }
  }

  // 洗牌，避免同维度的样本连续出现（跑评测时更真实）
  for (let i = rows.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[rows[i], rows[j]] = [rows[j], rows[i]]
  }

  const file = `${intent}.json`
  writeFileSync(resolve(outDir, file), JSON.stringify(rows, null, 2) + '\n', 'utf8')

  const byDim = {}
  for (const r of rows) byDim[r.dimension] = (byDim[r.dimension] ?? 0) + 1
  manifest.classes.push({ intent, tool, risk, needs_confirm: needsConfirm === 'true', count: rows.length, file, byDimension: byDim })
  manifest.totalSamples += rows.length
  allCount += rows.length
}

